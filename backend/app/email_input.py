import json
from typing import Annotated, Literal
from pydantic import BaseModel, ConfigDict, Field

GMAIL_CONTRACT_REVISION = '6e82068c34690506f932f5c73d054257bb2cb996'
EMAIL_PREPROCESS_VERSION = 'gmail-analysis-lf-v1'
TRANSFORMATION_VERSION = 'paired-body-gmail-wrapper-v1'


class Attachment(BaseModel):
    model_config = ConfigDict(extra='forbid', strict=True)
    filename: str
    content_type: str
    size_bytes: int | None
    disposition: str
    content_id: str
    is_inline: bool


class GmailEmail(BaseModel):
    """Exact keys and nullable types emitted by the inspected team parser."""
    model_config = ConfigDict(extra='forbid', strict=True)
    id: str
    thread_id: str
    subject: str
    sender: str
    received_at: str | None
    labels: list[str]
    text_plain: str
    text_html: str
    analysis_text: str
    attachments: list[Attachment]
    warnings: list[str]
    truncated: bool
    body_hash: str | None
    trust: Literal['UNTRUSTED']


class PartialEmail(BaseModel):
    """Evaluation-only projection. Null means unavailable, not a Gmail response."""
    model_config = ConfigDict(extra='forbid', strict=True)
    id: str | None = None
    thread_id: str | None = None
    subject: str | None = None
    sender: str | None = None
    received_at: str | None = None
    labels: list[str] | None = None
    text_plain: str | None = None
    text_html: str | None = None
    analysis_text: str
    attachments: list[Attachment] | None = None
    warnings: list[str] | None = None
    truncated: bool | None = None
    body_hash: str | None = None
    trust: Literal['UNTRUSTED']


class ParsedEnvelope(BaseModel):
    model_config = ConfigDict(extra='forbid')
    kind: Literal['gmail_parsed']
    content: GmailEmail


class BodyEnvelope(BaseModel):
    model_config = ConfigDict(extra='forbid')
    kind: Literal['body_only']
    content: PartialEmail


EmailEnvelope = Annotated[ParsedEnvelope | BodyEnvelope, Field(discriminator='kind')]


def sample_from_gmail(parsed_response, *, sample_id, label, **evaluation_metadata):
    """Adapt an existing collector response; no Gmail login, fetch or MIME parse.

    sample_id and gold label are supplied by the evaluator, never inferred from
    Gmail id/labels. Validation does not manufacture missing collector fields.
    """
    from .schemas import Sample
    return Sample.model_validate({**evaluation_metadata, 'sample_id':sample_id,
        'label':label, 'email':{'kind':'gmail_parsed','content':parsed_response}}).model_dump()


def normalize(value):
    return str(value or '').replace('\r\n', '\n').replace('\r', '\n')


def analysis_input(sample):
    """Only subject, sender, and already assembled analysis_text cross this boundary.

    MIME order cannot be recovered from aggregated plain/html fields. Parsed Gmail
    input MUST supply analysis_text as generated by the team parser. A source with
    just one body chunk uses that chunk verbatim; HTML is never parsed or removed.
    """
    envelope = sample.get('email')
    if not envelope:
        fields = {'subject': normalize(sample.get('subject')), 'body': normalize(sample.get('body'))}
    else:
        content = envelope['content']
        fields = {key: normalize(content[key]) for key in ('subject', 'sender') if content.get(key)}
        fields['body'] = normalize(content['analysis_text'])
    return json.dumps(fields, ensure_ascii=False, separators=(',', ':'))


def input_quality(sample):
    envelope = sample.get('email')
    content = envelope['content'] if envelope else {}
    parsed = bool(envelope and envelope['kind'] == 'gmail_parsed')
    errors = []
    if not (content.get('analysis_text') if envelope else sample.get('body') or '').strip():
        errors.append('analysis_text_missing')
    # Conservative MVP: incomplete Gmail collection is not given a valid threat
    # verdict. Body-only public inputs are explicitly evaluated over that scope.
    if parsed and (content.get('warnings') or content.get('truncated') or content.get('attachments')):
        errors.append('gmail_collection_incomplete_or_attachment_not_analyzed')
    return dict(assessment_scope='body_text_only',
                input_kind=envelope['kind'] if envelope else 'legacy_subject_body',
                collection_warnings=content.get('warnings'), collection_truncated=content.get('truncated'),
                attachments=content.get('attachments'), attachment_content_analyzed=False,
                original_body_hash=content.get('body_hash'), source_body_hash=sample.get('body_hash'),
                source_body_hash_method=sample.get('body_hash_method'),
                collection_completeness='unknown' if not parsed else ('incomplete' if errors else 'parsed_body'),
                truncation_policy='reject_over_limit_no_truncation', errors=errors,
                contract_revision=GMAIL_CONTRACT_REVISION if envelope else None)
